package format

// A bug file (bonsai.bug/1, set 14; plan P-T-6023) and the bugs page generated from the bug files (bonsai.bugs/1).
//
// A bug file is a markdown file whose frontmatter is the document, one per bug, in the folder bonsai.yaml names under
// documents.bug (workspace.DocKinds). Format 1 only: the format is new with set 14. bonsai check reads every one.
//
// The bugs page is a generated page like the two tables (table.go): its frontmatter holds only its format line, with
// the comment saying it is generated, and its body is written and read as formats/README.md ("The two tables'
// bodies") says: the line "# Bugs", a blank line, the generated line, a blank line, then the four sections Open,
// Watched, Fixed and Won't fix, each always written, each a heading, a blank line and one table of the same nine
// columns, a blank line between two sections. A row's status is its section's. The format line is the generated
// marker (BugsMarked): bonsai check --write writes the page only while it is missing or carries it.

import (
	"bytes"
	"strings"

	"github.com/LastStep/Bonsai/internal/schema"
)

// Bug is a bug file's frontmatter.
type Bug struct {
	ID      string        `json:"id"`     // BUG- and 3 to 6 digits
	Title   string        `json:"title"`  // one line
	Status  string        `json:"status"` // the closed list: open, fixed, wontfix, watched
	Area    *string       `json:"area"`
	Where   *string       `json:"where"`
	FoundBy *string       `json:"found_by"`
	FiledBy *string       `json:"filed_by"`
	FixedBy *string       `json:"fixed_by"`
	FixedIn *string       `json:"fixed_in"`
	Task    *string       `json:"task"`
	Was     *string       `json:"was"`
	Why     *string       `json:"why"`
	Created string        `json:"created"` // YYYY-MM-DD, the UTC day
	Closed  *string       `json:"closed"`  // YYYY-MM-DD, or null
	Labels  schema.Object `json:"labels"`
	Extra   schema.Object `json:"-"`
}

// ReadBug reads a bug file's bytes (format 1 only).
func ReadBug(raw []byte) (*Bug, error) {
	b := &Bug{}
	if _, err := MustLookup("bug").readYAMLInto(raw, b); err != nil {
		return nil, err
	}
	return b, nil
}

// Bugs is the bugs page.
type Bugs struct {
	Bugs  []BugRow      `json:"bugs"` // the rows, open ones first (BugSections' order), each section newest id first
	Extra schema.Object `json:"-"`    // frontmatter fields this Bonsai does not know
}

// BugRow is one bug's row.
type BugRow struct {
	ID      string        `json:"id"`
	Title   string        `json:"title"`
	Status  string        `json:"status"`
	Area    *string       `json:"area"`
	Where   *string       `json:"where"`
	FoundBy *string       `json:"found_by"`
	FixedIn *string       `json:"fixed_in"`
	Task    *string       `json:"task"`
	Closed  *string       `json:"closed"`
	Why     *string       `json:"why"`
	Extra   schema.Object `json:"-"`
}

// BugSection is one section of the bugs page: its status and its heading.
type BugSection struct {
	Status  string
	Heading string
}

// BugSections are the page's sections, in the page's order: the open ones first. Every status of bonsai.bug/1 has
// one (TestBugSectionsAreTheStatuses holds them to its schema, the list's one home).
var BugSections = []BugSection{{"open", "Open"}, {"watched", "Watched"}, {"fixed", "Fixed"}, {"wontfix", "Won't fix"}}

const (
	bugsComment  = "generated by bonsai check --write from the bug files; never edit by hand"
	bugsTitle    = "# Bugs"
	bugsLine     = "Generated from the bug files; never edit by hand. To file a bug or move one: bonsai bug (skill base:bug)."
	bugsMarkerAt = "format: bonsai.bugs/"
)

var (
	bugsHeader = []string{"Bug", "Title", "Area", "Where", "Found by", "Fixed in", "Task", "Closed", "Why"}
	bugKeys    = []string{"id", "title", "area", "where", "found_by", "fixed_in", "task", "closed", "why"}
)

// Encode writes the bugs page, held to bonsai.bugs/1. Its rows are written in the section of their status, in the
// order given; a row whose status has no section is refused by the schema check before a byte is written (the
// schema's status is text, so it is refused here).
func (p *Bugs) Encode() ([]byte, error) {
	f := MustLookup("bugs")
	doc, err := f.tableDoc(p)
	if err != nil {
		return nil, err
	}
	rows, _ := doc.Get("bugs")
	bySection := map[string][]any{}
	for i, r := range rows.([]any) {
		st, _ := r.(schema.Object).Get("status")
		s, _ := st.(string)
		if !bugSection(s) {
			return nil, f.refuse(0, "bugs["+itoa(i)+"].status", "the status %s has no section on the page (open, watched, fixed, wontfix)", quoteASCII(s))
		}
		bySection[s] = append(bySection[s], r)
	}
	var b strings.Builder
	if err := frontmatter(&b, f, bugsComment, p.Extra); err != nil {
		return nil, err
	}
	b.WriteString(bugsTitle + "\n\n" + bugsLine + "\n")
	for _, s := range BugSections {
		b.WriteString("\n## " + s.Heading + "\n\n")
		writeTable(&b, bugsHeader, bySection[s.Status], bugKeys)
	}
	return []byte(b.String()), nil
}

func bugSection(status string) bool {
	for _, s := range BugSections {
		if s.Status == status {
			return true
		}
	}
	return false
}

// ReadBugs reads the bugs page's bytes: the frontmatter, then the body.
func ReadBugs(raw []byte) (*Bugs, error) {
	f := MustLookup("bugs")
	front, body, first, err := f.tableParts(raw)
	if err != nil {
		return nil, err
	}
	tb := &tableBody{f: f, lines: body, no: first}
	for _, want := range []string{bugsTitle, "", bugsLine} {
		if l, n := tb.next(); l != want {
			return nil, f.refuse(n, "bugs", "the line is not %s", quoteASCII(want))
		}
	}
	all := []any{}
	for _, s := range BugSections {
		for _, want := range []string{"", "## " + s.Heading, ""} {
			if l, n := tb.next(); l != want {
				return nil, f.refuse(n, "bugs", "the line is not %s", quoteASCII(want))
			}
		}
		rows, err := tb.table(bugsHeader, "bugs", bugKeys, map[string]bool{"area": true, "where": true, "found_by": true,
			"fixed_in": true, "task": true, "closed": true, "why": true}, nil)
		if err != nil {
			return nil, err
		}
		for _, r := range rows {
			o := r.(schema.Object)
			// The status, read from the section, goes third, in the schema's order.
			row := append(schema.Object{}, o[:2]...)
			row = append(row, schema.Member{Key: "status", Value: s.Status})
			all = append(all, append(row, o[2:]...))
		}
	}
	if err := tb.end(); err != nil {
		return nil, err
	}
	doc := append(front, schema.Member{Key: "bugs", Value: all})
	if doc, err = f.hold(doc, nil); err != nil {
		return nil, err
	}
	p := &Bugs{}
	return p, f.Bind(doc, p)
}

// BugsMarked reports whether a bugs page carries the generated marker: its frontmatter's first line is a format line
// naming bonsai.bugs (any major), after an optional byte order mark and with LF or CRLF line ends. A hand-kept
// register (a project before it moved its register to bug files) does not, and is never overwritten. A cheap read of
// the bytes, so the guard (stage 2) can judge it with no parse.
func BugsMarked(raw []byte) bool {
	raw = bytes.TrimPrefix(raw, []byte("\xef\xbb\xbf"))
	rest, ok := bytes.CutPrefix(raw, []byte("---\n"))
	if !ok {
		if rest, ok = bytes.CutPrefix(raw, []byte("---\r\n")); !ok {
			return false
		}
	}
	return bytes.HasPrefix(rest, []byte(bugsMarkerAt))
}

// bugComment is the pointer comment on a bug file's format line (contract §2.8).
const bugComment = "fields: bonsai check --schema bonsai.bug; how to fill: skill base:bug"

// ReadBugFile reads a bug file's bytes: its frontmatter (ReadBug) and its body, the text after the frontmatter's
// closing --- line and the one blank line after it, line endings read as LF.
func ReadBugFile(raw []byte) (*Bug, string, error) {
	b, err := ReadBug(raw)
	if err != nil {
		return nil, "", err
	}
	body, _ := markdownBody(raw)
	return b, body, nil
}

// Object gives the bug's frontmatter as bonsai.bug/1 holds it, checked against its schema: format first, every field
// in the schema's order, then any field this Bonsai does not know, kept.
func (b *Bug) Object() (schema.Object, error) {
	f := MustLookup("bug")
	doc, err := f.Document(b)
	if err != nil {
		return nil, err
	}
	if err := f.Check(doc); err != nil {
		return nil, err
	}
	return doc, nil
}

// EncodeFile writes the bug's file, held to bonsai.bug/1: the frontmatter (Object's fields), its format line carrying
// its pointer comment, then, when body is not empty, a blank line and the body as given. LF line endings.
func (b *Bug) EncodeFile(body string) ([]byte, error) {
	doc, err := b.Object()
	if err != nil {
		return nil, err
	}
	y, err := yamlDocument(doc, YAMLOptions{})
	if err != nil {
		return nil, err
	}
	_, rest, _ := strings.Cut(string(y), "\n") // the format line, written with its comment below
	var w strings.Builder
	w.WriteString("---\nformat: " + MustLookup("bug").Versioned() + "   # " + bugComment + "\n" + rest + "---\n")
	if body != "" {
		w.WriteString("\n" + strings.ReplaceAll(body, "\r\n", "\n"))
	}
	return []byte(w.String()), nil
}

