package engine

// Base's two skills generated whole from the templates the engine writes (plan-5 5.5.0 note 3: one home for each
// template). A template the engine writes, bonsai.yaml's (config.go) and STATE's (state.go), lives in the engine, since
// a project may link without base; base's workspace and state skills are built from it and from its format's schema
// by go generate (internal/reference/gen), each whole: its frontmatter, what the file is for, when to use the skill,
// the fields table (spec §5: | Field | Meaning | Allowed values | Example |) and the template as init writes it. A test
// rebuilds each and fails on any difference from the committed file, as the reference page's does, so a template and
// its skill cannot drift; check --pack holds each to its rules (pack-fields, pack-values) as it holds any template
// skill.
//
// The fields table: one row per field of the schema, nested ones by their path (packs[].ref, documents.task), a
// generated kind's two fields once for every kind (generated.<kind>.keep_days); the meaning is the template's own
// comment for the field (Comments, StateFields); the allowed values a closed list's values in backquotes (the
// schema's enum or const, as check --pack reads them: schemaList), else the field's type in words (a pattern in
// backquotes); the example the schema's first, as JSON, or "as in the template" where that is long. Byte-stable: LF,
// ASCII, no map-order iteration.

import (
	"fmt"
	"strings"

	"github.com/LastStep/Bonsai/internal/format"
	"github.com/LastStep/Bonsai/internal/schema"
	"github.com/LastStep/Bonsai/internal/workspace"
)

// Where go generate writes the two skills, from the repository's root: base's skills folder.
const (
	WorkspaceSkillPath = "packs/base/skills/workspace/SKILL.md"
	StateSkillPath     = "packs/base/skills/state/SKILL.md"
)

// GeneratedNote is the comment at the top of every file go generate writes into a pack: what writes it and how a
// change is made.
const GeneratedNote = "<!-- Generated by go generate from Bonsai's code (internal/reference/gen); never edit it by hand: a test " +
	"rebuilds it and fails on any difference. -->"

// The example values the workspace skill's template shows where init writes a project's own.
const (
	exampleID     = "ws-abcdefghijklmnopqrstuvwxyz"
	exampleSource = "https://example.com/packs/example-pack.git"
)

// exampleLadder is the workspace skill's example of a two-rung ladder (note 5: init writes none, since a project's
// rungs are its own): the guard rung and a test rung, both on the floor, its count a ratchet. TestWorkspaceSkill reads
// it as part of a bonsai.yaml.
const exampleLadder = `ladder_floor: [0, 1]                  # every task climbs both rungs
ladder:                               # the rungs, cheapest first
  - rung: 0                           # rung 0: the guard rung
    name: "guard"                     # its short name
    kind: guard                       # the branch's changes against the running task's grants
    command: null                     # only a command rung runs a command
    required: true                    # red here skips the rungs after it
    timeout_s: 120                    # two minutes
    ratchet: null                     # no count to keep from falling
    capture: null                     # nothing picked out of its output
    means: "Every change is inside the task's grants."   # what green proves
    tests: null                       # it prints no tests
    base_setup: null                  # nothing to set up on the base
  - rung: 1                           # the project's tests
    name: "tests"                     # its short name
    kind: command                     # a shell command, the same in sh and cmd
    command: "go test -json ./..."    # the project's own test command
    required: true                    # red here skips the rungs after it
    timeout_s: 600                    # ten minutes
    ratchet: tests                    # its count, the tests that passed, may not fall below ratchets.tests
    capture: null                     # the count is read from the tests themselves
    means: "Every test passes, and no fewer than the floor."   # what green proves
    tests: go-test-json               # its output's form: each test named
    base_setup: null                  # nothing to set up on the base
ratchets:                             # counts that may only rise
  tests: 0                            # raised to a green climb's count once there is one
`

// WorkspaceSkill is base's workspace skill (WorkspaceSkillPath): bonsai.yaml's template as init writes it, from
// ConfigYAML, Comments and bonsai.workspace/1's schema.
func WorkspaceSkill() []byte {
	f := format.MustLookup("workspace")
	tmpl, err := ConfigYAML(exampleID, InitValues{Name: "example", Source: exampleSource, Ref: "v1.0.0"},
		&PackData{Manifest: &workspace.Pack{ID: "example-pack"}})
	if err != nil {
		panic("engine: bonsai.yaml's template does not write: " + err.Error()) // TestWorkspaceSkill rules it out
	}
	c := comment(nil)
	var b strings.Builder
	line := func(s string) { b.WriteString(s + "\n") }
	line("---")
	line("name: workspace")
	line(`description: "bonsai.yaml, this project's Bonsai settings: what each field means, its allowed values and the template ` +
		`bonsai init writes. Use it to read or change a setting: a pack's ref or its roles' limits, where documents live, the ` +
		`protected paths, the ladder, how long generated files are kept."`)
	line("---")
	line("")
	line(GeneratedNote)
	line("")
	line("# bonsai.yaml: this project's Bonsai settings")
	line("")
	line("**What it is.** `bonsai.yaml`, at the project's top folder, holds the project's Bonsai settings in the format " +
		"`bonsai.workspace/1`: the packs it links and their refs, where it keeps the documents Bonsai knows, the paths agents " +
		"change only under a grant, the ladder that proves work done, how long generated files are kept, and the limits of " +
		"its packs' roles. It is the one Bonsai file a person edits. `bonsai init` writes it from the template below, a " +
		"comment on every key; a writer keeps the comments, and `bonsai check` does not require them.")
	line("")
	line("**When to use this skill.** Before reading or changing a setting: what a field means, the values it takes, and " +
		"what changing it does. Every field and every allowed value is also printed by `bonsai check --schema bonsai.workspace`.")
	line("")
	line("**How a change takes effect.** The file is committed and person-only: an agent changes it only while its running " +
		"task's `bonsai.allows` holds it, which a person grants. A pack's ref, a pack added or taken out, `never_edit` and " +
		"the folders under `documents` take effect at `bonsai update` (it previews every change; `--yes` writes them). The " +
		"ladder, its floor, the ratchets and `ci_marked_tests` count as committed at the main checkout's HEAD, and one that " +
		"sets a check looser (a rung or a floor entry taken out or changed, a rung added, a ratchet lowered) waits for a " +
		"person's `bonsai update` to record it. A role's limits under `packs[].roles` and the `messages` thresholds change any " +
		"time: raising a default or a max is never a loosening.")
	line("")
	line("## Fields")
	line("")
	line("| Field | Meaning | Allowed values | Example |")
	line("|---|---|---|---|")
	for _, r := range fieldRows(f, c) {
		line(r)
	}
	line("")
	line("## The template")
	line("")
	line("What `bonsai init` writes, every field present and a comment on every key; its id, name and pack are the project's own " +
		"(here placeholders). Its ladder is empty: a project's rungs are its own, since only it knows its test command.")
	line("")
	line("```yaml")
	b.Write(tmpl)
	line("```")
	line("")
	line("## An example ladder")
	line("")
	line("Two rungs a project might add: the guard rung and its own tests, both on the floor. A rung added is a person's step: " +
		"the next climb refuses it until a person's `bonsai update` in the main checkout records it.")
	line("")
	line("```yaml")
	b.WriteString(exampleLadder)
	line("```")
	return []byte(b.String())
}

// StateSkill is base's state skill (StateSkillPath): STATE's template as init writes it, from StateTemplate,
// StateFields and bonsai.state/1's schema.
func StateSkill() []byte {
	f := format.MustLookup("state")
	meaning := map[string]string{}
	for _, sf := range StateFields {
		meaning[sf.Field] = sf.Meaning
	}
	var b strings.Builder
	line := func(s string) { b.WriteString(s + "\n") }
	line("---")
	line("name: state")
	line(`description: "STATE, the one page that says where a project stands (.bonsai/STATE.md, bonsai.state/1): its fields, ` +
		`their allowed values and its template. Use it to rewrite STATE, or to add one to a project that has none."`)
	line("---")
	line("")
	line(GeneratedNote)
	line("")
	line("# STATE: where the project stands")
	line("")
	line("**What it is.** `.bonsai/STATE.md` is one page, in the format `bonsai.state/1`: a short frontmatter and a free " +
		"body saying where the project stands now, what is next, what is open and what was decided lately. Every project " +
		"has it at that place (it is no `bonsai.yaml` setting). It is committed and not person-only.")
	line("")
	line("**When to use this skill.** A new session reads STATE first. Rewrite it whole, never append, whenever where the " +
		"project stands changes, and set `updated` and `updated_by` as you do. `bonsai init` writes it from the template " +
		"below when the project has none (from then on it is the project's: no update writes over it, and `bonsai unlink` " +
		"leaves it); a project linked before it had one writes it from the template itself. Its fields and allowed values " +
		"are also printed by `bonsai check --schema bonsai.state`.")
	line("")
	line("## Fields")
	line("")
	line("| Field | Meaning | Allowed values | Example |")
	line("|---|---|---|---|")
	for _, r := range fieldRows(f, func(path string) string { return meaning[path] }) {
		line(r)
	}
	line("")
	line("## The template")
	line("")
	line("What `bonsai init` writes, `updated` set to the day it runs:")
	line("")
	line("```markdown")
	b.Write(StateTemplate("YYYY-MM-DD"))
	line("```")
	return []byte(b.String())
}

// fieldRows are a format's fields table rows: one per field of its schema (nested ones by path; a generated kind's
// two fields once, as generated.<kind>.keep_days), with meaning's words.
func fieldRows(f *format.Format, meaning func(path string) string) []string {
	var rows []string
	kindDone := false
	var walk func(o schema.Object, at string)
	walk = func(o schema.Object, at string) {
		props, _ := o.Get("properties")
		po, _ := props.(schema.Object)
		for _, m := range po {
			path := m.Key
			if at != "" {
				path = at + "." + m.Key
			}
			ps := m.Value.(schema.Object)
			if at == "generated" && path != "generated."+format.GeneratedKinds[0].Kind {
				// Each generated kind has the same two fields: its own row, and the fields' rows once, below the first.
				rows = append(rows, tableRow(f, path, meaning(path), ps))
				continue
			}
			if at == "generated" && !kindDone {
				kindDone = true
				rows = append(rows, tableRow(f, path, meaning(path), ps))
				kp, _ := ps.Get("properties")
				for _, k := range kp.(schema.Object) {
					p := "generated.<kind>." + k.Key
					rows = append(rows, tableRow(f, p, meaning("generated."+format.GeneratedKinds[0].Kind+"."+k.Key), k.Value.(schema.Object)))
				}
				continue
			}
			rows = append(rows, tableRow(f, path, meaning(path), ps))
			if items, ok := ps.Get("items"); ok {
				if io, ok := items.(schema.Object); ok {
					if _, ok := io.Get("properties"); ok {
						walk(io, path+"[]")
					}
				}
			}
			walk(ps, path)
		}
	}
	walk(f.Schema(), "")
	return rows
}

// tableRow is one row of a fields table.
func tableRow(f *format.Format, path, meaning string, ps schema.Object) string {
	allowed := ""
	if vals := schemaList(f.Schema(), path); len(vals) > 0 {
		allowed = backquote(vals)
		if nullable(ps) {
			allowed += ", or null"
		}
	} else {
		allowed = typeWords(ps)
	}
	example := "as in the template"
	if ex, ok := ps.Get("examples"); ok {
		if list, ok := ex.([]any); ok && len(list) > 0 {
			if s := schema.Show(list[0]); len(s) <= 60 {
				example = "`" + s + "`"
			}
		}
	}
	if meaning == "" {
		meaning = "-"
	}
	cell := func(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
	return "| `" + path + "` | " + cell(upperFirst(meaning)) + " | " + cell(allowed) + " | " + cell(example) + " |"
}

// typeWords says a field's type in words: text (matching a pattern), a whole number (from its minimum), true or false,
// a list of its items' type, a mapping; "or null" where null is allowed; "any value" where the schema gives no type.
func typeWords(ps schema.Object) string {
	var types []string
	switch t, _ := ps.Get("type"); x := t.(type) {
	case string:
		types = []string{x}
	case []any:
		for _, e := range x {
			if s, ok := e.(string); ok {
				types = append(types, s)
			}
		}
	}
	var words []string
	null := false
	for _, t := range types {
		switch t {
		case "null":
			null = true
		case "string":
			w := "text"
			if p, ok := ps.Get("pattern"); ok {
				w += " matching `" + fmt.Sprint(p) + "`"
			}
			words = append(words, w)
		case "integer":
			w := "a whole number"
			if m, ok := ps.Get("minimum"); ok {
				w += " from " + schema.Show(m)
			}
			words = append(words, w)
		case "number":
			words = append(words, "a number")
		case "boolean":
			words = append(words, "true or false")
		case "array":
			w := "a list"
			if items, ok := ps.Get("items"); ok {
				if io, ok := items.(schema.Object); ok {
					if _, has := io.Get("properties"); has {
						w += " of mappings (their fields below)"
					} else if inner := typeWords(io); inner != "any value" {
						w += " of " + inner
					}
				}
			}
			words = append(words, w)
		case "object":
			w := "a mapping"
			if _, has := ps.Get("properties"); has {
				w += " (its fields below)"
			}
			words = append(words, w)
		}
	}
	if len(words) == 0 {
		words = []string{"any value"}
	}
	s := strings.Join(words, ", or ")
	if null {
		s += ", or null"
	}
	return s
}

// nullable reports whether a field's schema allows null.
func nullable(ps schema.Object) bool {
	if t, ok := ps.Get("type"); ok {
		if list, ok := t.([]any); ok {
			for _, e := range list {
				if e == "null" {
					return true
				}
			}
		}
	}
	return false
}

// upperFirst gives a sentence its capital letter.
func upperFirst(s string) string {
	if s == "" || s[0] < 'a' || s[0] > 'z' {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
