package guard

// The guard's hold on bugs (plan P-T-6023, step 9): a bug file's status line in every mode (bonsai bug alone moves a
// bug; a new bug file by hand starts at open), with tasks' rule left as it is; the bugs page refused to edits and
// deletes while it carries the generated marker, and an ordinary file while it does not (a register not moved yet);
// bonsai bug's writing subcommands refused to a role that changes nothing.

import (
	"strings"
	"testing"
)

const (
	bugFile   = "work/bugs/BUG-001.md"
	bugsPage  = "work/bugs.md"
	markedTop = "---\nformat: bonsai.bugs/1   # generated by bonsai check --write from the bug files; never edit by hand\n---\n\n# Bugs\n"
	handKept  = "---\ntitle: Known bugs\n---\n\n# Known bugs\n\n| Bug | Title |\n|---|---|\n| TB-001 | One |\n"
)

func bugText(id, status string) string {
	return "---\nformat: bonsai.bug/1\nid: " + id + "\ntitle: One\nstatus: " + status + "\narea: null\nwhere: null\nfound_by: null\n" +
		"filed_by: person\nfixed_by: null\nfixed_in: null\ntask: null\nwas: null\nwhy: null\ncreated: 2026-10-11\nclosed: null\n" +
		"labels: {}\n---\n\nHow to repeat it.\n"
}

func bugProject(t *testing.T, page string) string {
	t.Helper()
	files := map[string]string{"work/tasks/T-0001-the-task.md": taskText("T-0001", "todo", "light"), bugFile: bugText("BUG-001", "open")}
	if page != "" {
		files[bugsPage] = page
	}
	return grantProject(t, "", files)
}

// A bug's status line, in both modes: refused, naming bonsai bug; its other lines free; a new file at open only; a
// delete refused (what it leaves cannot be shown to keep the line).
func TestABugsStatusLineInEveryMode(t *testing.T) {
	for _, mode := range []string{"agents", "command"} {
		t.Run(mode, func(t *testing.T) {
			dir := bugProject(t, "")
			if mode == "command" {
				commandMode(t, dir)
			}
			s := wantRule(t, dir, editIn(dir, bugFile, "status: open", "status: fixed"), RuleStatusLine)
			if !strings.Contains(s, "a bug's status changes only by bonsai bug, in every project") || !strings.Contains(s, "bonsai bug (fix <id> --commit") {
				t.Errorf("the refusal names bonsai bug: %s", s)
			}
			wantRule(t, dir, writeOf(dir, bugFile, bugText("BUG-001", "wontfix")), RuleStatusLine)
			wantRule(t, dir, editIn(dir, bugFile, "title: One", "title: One, again"), RuleNotProtected)
			wantRule(t, dir, editIn(dir, bugFile, "How to repeat it.", "How to repeat it: restart."), RuleNotProtected)
			wantRule(t, dir, writeOf(dir, "work/bugs/BUG-002.md", bugText("BUG-002", "open")), RuleNotProtected)
			wantRule(t, dir, writeOf(dir, "work/bugs/BUG-003.md", bugText("BUG-003", "fixed")), RuleStatusLine)
			wantRule(t, dir, bashIn(dir, "Bash", "rm "+bugFile), RuleDeleteProtected) // judged as an edit: status-line
			// A broken bug file: command mode's bad-format, as a task's; free in agents mode (check names it).
			formatWant := RuleNotProtected
			if mode == "command" {
				formatWant = RuleBadFormat
			}
			wantRule(t, dir, editIn(dir, bugFile, "title: One", "title: [One"), formatWant)
			// A file in the folder not named by a bug id is no bug file: free.
			wantRule(t, dir, writeOf(dir, "work/bugs/notes.md", "status: fixed\n"), RuleNotProtected)
			// Tasks' rule is as it was: free in agents mode, the status command's in command mode.
			taskWant := RuleNotProtected
			if mode == "command" {
				taskWant = RuleStatusLine
			}
			wantRule(t, dir, editIn(dir, "work/tasks/T-0001-the-task.md", "status: todo", "status: running"), taskWant)
		})
	}
}

// The bugs page: refused to edits and deletes while it carries the generated marker, in both modes and under any
// grant; a hand-kept register (no marker) is edited and deleted as any file.
func TestTheBugsPageOnlyWhileMarked(t *testing.T) {
	for _, mode := range []string{"agents", "command"} {
		t.Run(mode, func(t *testing.T) {
			dir := bugProject(t, markedTop)
			if mode == "command" {
				commandMode(t, dir)
			}
			s := wantRule(t, dir, editIn(dir, bugsPage, "# Bugs", "# Our bugs"), RuleBonsaiFiles)
			if !strings.Contains(s, "generated marker") || !strings.Contains(s, "bonsai check --write") {
				t.Errorf("the page's refusal: %s", s)
			}
			wantRule(t, dir, writeOf(dir, bugsPage, handKept), RuleBonsaiFiles)
			wantRule(t, dir, bashIn(dir, "Bash", "rm "+bugsPage), RuleDeleteProtected)
			wantRule(t, dir, bashIn(dir, "Bash", "rm -r work"), RuleDeleteProtected)

			dir = bugProject(t, handKept)
			if mode == "command" {
				commandMode(t, dir)
			}
			wantRule(t, dir, editIn(dir, bugsPage, "| TB-001 | One |", "| TB-001 | One, fixed |"), RuleNotProtected)
			wantRule(t, dir, writeOf(dir, bugsPage, markedTop), RuleNotProtected) // a page made, its marker added: Bonsai's from then
			wantRule(t, dir, bashIn(dir, "Bash", "rm "+bugsPage), RuleDeleteNamed)
		})
	}
	// The page's place follows bonsai.yaml's documents.bugs.
	yaml := strings.Replace(grantYAML, "  run: work/runs\n", "  run: work/runs\n  bugs: records/bugs.md\n", 1)
	dir := grantProject(t, yaml, map[string]string{"records/bugs.md": markedTop, bugsPage: markedTop})
	wantRule(t, dir, editIn(dir, "records/bugs.md", "# Bugs", "# x"), RuleBonsaiFiles)
	wantRule(t, dir, editIn(dir, bugsPage, "# Bugs", "# x"), RuleNotProtected)
	wantRule(t, dir, writeOf(dir, "records/bugs/BUG-001.md", bugText("BUG-001", "fixed")), RuleStatusLine)
}

// bonsai bug's writing subcommands are writes: refused to a role that changes nothing; list and show are not.
func TestBugWritesForARoleThatChangesNothing(t *testing.T) {
	dir := briefProject(t)
	started(t, dir, sessA, "workflow:verifier")
	agent := ChildSessionEnv
	verifier := func(cmd string) string { return shellAs(dir, "v1", "workflow:verifier", cmd, false) }
	for _, c := range []string{"bonsai bug add --title x --by verifier", "bonsai bug fix BUG-001 --commit abcd1234",
		"bonsai bug wontfix BUG-001 --why x", "bonsai bug watch BUG-001 --why x", "bonsai bug reopen BUG-001",
		"bonsai bug edit BUG-001 --title y", "bonsai bug $SUB BUG-001"} {
		wantAnswer(t, dir, verifier(c), 2, RuleRoleWritesNothing, agent, "1")
	}
	for _, c := range []string{"bonsai bug list --json", "bonsai bug show BUG-001", "bonsai bug --help"} {
		if code, s := runs(t, dir, verifier(c), agent, "1"); code != 0 {
			t.Errorf("a verifier, %s: exit %d: %s", c, code, s)
		}
	}
}
